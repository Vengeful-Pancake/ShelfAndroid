package com.shelf.reader.epub

import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.File
import java.io.RandomAccessFile
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

class EpubBookTest {

    @Test
    fun calibreExportCountsOnlyTheRealChapter() {
        withBook(sampleEntries()) { book ->
            assertEquals("Thượng hạng gia đinh", book.meta.title)
            assertEquals("", book.meta.description)
            assertEquals(1, book.chapterCount)
            assertEquals(1, book.meta.chapters)
            assertEquals(listOf("index_split_002.html"), book.spine)
            assertEquals(
                listOf(
                    EpubSectionKind.COVER,
                    EpubSectionKind.TITLE_PAGE,
                    EpubSectionKind.CONTENTS,
                ),
                book.auxiliarySections.map(EpubSection::kind),
            )
            assertEquals(1, book.toc.size)
            assertEquals("Chương 1: Thượng hạng gia đinh", book.toc.single().label)
            assertEquals(0, book.toc.single().spineIndex)
            assertEquals(0, book.readingIndexForPackageIndex(0))
            assertEquals(0, book.readingIndexForPackageIndex(3))
        }
    }

    @Test
    fun aShortUnlabelledDocumentIsNotDiscarded() {
        val entries = sampleEntries().toMutableMap().apply {
            put(
                "content.opf",
                getValue("content.opf").replace(
                    "<itemref idref=\"chapter\"/>",
                    "<itemref idref=\"short\"/><itemref idref=\"chapter\"/>",
                ).replace(
                    "<item id=\"chapter\"",
                    "<item id=\"short\" href=\"scene.html\" media-type=\"application/xhtml+xml\"/><item id=\"chapter\"",
                ),
            )
            put("scene.html", "<html><head><title>The book</title></head><body><p>A brief scene.</p></body></html>")
        }

        withBook(entries) { book ->
            assertEquals(2, book.chapterCount)
            assertTrue("scene.html" in book.spine)
        }
    }

    private fun withBook(entries: Map<String, String>, block: (EpubBook) -> Unit) {
        val file = File.createTempFile("shelf-epub-", ".epub")
        try {
            ZipOutputStream(file.outputStream()).use { zip ->
                entries.forEach { (name, text) ->
                    zip.putNextEntry(ZipEntry(name))
                    zip.write(text.toByteArray(Charsets.UTF_8))
                    zip.closeEntry()
                }
            }
            val channel = RandomAccessFile(file, "r").channel
            EpubBook(ZipReader.open(channel)).use(block)
        } finally {
            file.delete()
        }
    }

    private fun sampleEntries(): Map<String, String> = linkedMapOf(
        "META-INF/container.xml" to """
            <container xmlns="urn:oasis:names:tc:opendocument:xmlns:container" version="1.0">
              <rootfiles><rootfile full-path="content.opf" media-type="application/oebps-package+xml"/></rootfiles>
            </container>
        """.trimIndent(),
        "content.opf" to """
            <package xmlns="http://www.idpf.org/2007/opf" version="2.0" unique-identifier="book-id">
              <metadata xmlns:dc="http://purl.org/dc/elements/1.1/">
                <dc:title>(Thượng hạng gia đinh</dc:title>
                <dc:creator>Tàng Thư Studio</dc:creator>
                <dc:language>vi</dc:language>
                <dc:description>generated by python-docx</dc:description>
                <dc:identifier id="book-id">test-book</dc:identifier>
              </metadata>
              <manifest>
                <item id="cover-page" href="titlepage.xhtml" media-type="application/xhtml+xml"/>
                <item id="title" href="index_split_000.html" media-type="application/xhtml+xml"/>
                <item id="contents" href="index_split_001.html" media-type="application/xhtml+xml"/>
                <item id="chapter" href="index_split_002.html" media-type="application/xhtml+xml"/>
                <item id="ncx" href="toc.ncx" media-type="application/x-dtbncx+xml"/>
              </manifest>
              <spine toc="ncx">
                <itemref idref="cover-page"/><itemref idref="title"/>
                <itemref idref="contents"/><itemref idref="chapter"/>
              </spine>
            </package>
        """.trimIndent(),
        "toc.ncx" to """
            <ncx xmlns="http://www.daisy.org/z3986/2005/ncx/" version="2005-1">
              <navMap><navPoint id="chapter-1"><navLabel><text>Chương 1: Thượng hạng gia đinh</text></navLabel>
                <content src="index_split_002.html"/></navPoint></navMap>
            </ncx>
        """.trimIndent(),
        "titlepage.xhtml" to """
            <html><head><title>Cover</title></head><body><svg><image href="cover.jpg"/></svg></body></html>
        """.trimIndent(),
        "index_split_000.html" to """
            <html><head><title>(Thượng hạng gia đinh</title></head><body><p>(Thượng hạng gia đinh</p></body></html>
        """.trimIndent(),
        "index_split_001.html" to """
            <html><head><title>(Thượng hạng gia đinh</title></head><body><p>MỤC LỤC</p>
              <a href="index_split_002.html#chapter-1">Chương 1: Thượng hạng gia đinh</a></body></html>
        """.trimIndent(),
        "index_split_002.html" to """
            <html><head><title>(Thượng hạng gia đinh</title></head><body>
              <h1 id="chapter-1">Chương 1: Thượng hạng gia đinh</h1><p>Actual reading text.</p>
            </body></html>
        """.trimIndent(),
    )
}
